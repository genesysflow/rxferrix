    // How ts-rs 12 reports dependencies, as seen through `ts_inline` in a session.
    mod deps {
        use std::collections::HashMap;

        use super::super::with_session;
        use crate::private::ts_inline;

        #[derive(ts_rs::TS)]
        #[allow(dead_code)]
        enum Status {
            Open,
            Done,
        }
        #[derive(ts_rs::TS)]
        #[allow(dead_code)]
        struct Inner {
            status: Status,
            big: u64,
        }
        #[derive(ts_rs::TS)]
        #[allow(dead_code)]
        struct Outer {
            list: Vec<Status>,
            maybe: Option<Status>,
            map: HashMap<String, Status>,
            inner: Inner,
        }
        #[derive(ts_rs::TS)]
        #[allow(dead_code)]
        struct OnlyGenerics {
            list: Vec<Inner>,
        }
        #[derive(ts_rs::TS)]
        #[allow(dead_code)]
        struct Page<T> {
            items: Vec<T>,
        }
        #[derive(ts_rs::TS)]
        #[allow(dead_code)]
        struct UsesPage {
            page: Page<Status>,
        }

        fn names(decls: &[super::TypeDecl]) -> Vec<&str> {
            decls.iter().map(|d| d.name.as_str()).collect()
        }

        #[test]
        fn fields_are_named_and_collected_recursively() {
            let (ts, decls) = with_session(ts_inline::<Outer>).unwrap();
            assert_eq!(
                ts,
                "{ list: Array<Status>, maybe: Status | null, map: { [key in string]: Status }, inner: Inner, }"
            );
            // Vec / Option / HashMap report their type parameters; `Inner` brings `Status` again (deduplicated).
            assert_eq!(names(&decls), ["Inner", "Status"]);
            let inner = &decls[0].decl;
            assert_eq!(inner, "export type Inner = { status: Status, big: number, };");
            assert_eq!(decls[1].decl, "export type Status = \"Open\" | \"Done\";");
        }

        #[test]
        fn top_level_wrappers_inline_their_parameter() {
            // `Vec<Status>` inlines `Status`, so nothing needs declaring.
            let (ts, decls) = with_session(ts_inline::<Vec<Status>>).unwrap();
            assert_eq!(ts, "Array<\"Open\" | \"Done\">");
            assert!(decls.is_empty());
            let (ts, decls) = with_session(ts_inline::<Option<HashMap<String, Inner>>>).unwrap();
            assert_eq!(ts, "{ [key in string]: { status: Status, big: number, } } | null");
            assert_eq!(names(&decls), ["Status"]);
            let (ts, decls) = with_session(ts_inline::<OnlyGenerics>).unwrap();
            assert_eq!(ts, "{ list: Array<Inner>, }");
            assert_eq!(names(&decls), ["Inner", "Status"]);
        }

        #[test]
        fn generic_user_types_are_declared_generically() {
            let (ts, decls) = with_session(ts_inline::<UsesPage>).unwrap();
            assert_eq!(ts, "{ page: Page<Status>, }");
            assert_eq!(names(&decls), ["Page", "Status"]);
            assert_eq!(decls[0].decl, "export type Page<T> = { items: Array<T>, };");
        }

        #[test]
        fn top_level_generic_user_types_are_named_and_declared() {
            // e.g. `PaginationResult<Doc<..>>` outputs: referred to by name, with the generic declaration emitted.
            let (ts, decls) = with_session(ts_inline::<Page<Inner>>).unwrap();
            assert_eq!(ts, "Page<Inner>");
            assert_eq!(names(&decls), ["Inner", "Page", "Status"]);
            assert_eq!(decls[1].decl, "export type Page<T> = { items: Array<T>, };");
            let (ts, decls) = with_session(ts_inline::<Page<String>>).unwrap();
            assert_eq!(ts, "Page<string>");
            assert_eq!(names(&decls), ["Page"]);
            // Outside a session: just the name.
            assert_eq!(ts_inline::<Page<Status>>(), "Page<Status>");
        }

        #[test]
        fn no_session_no_collection() {
            assert_eq!(ts_inline::<Inner>(), "{ status: Status, big: number, }");
            let ((), decls) = with_session(|| ()).unwrap();
            assert!(decls.is_empty(), "nothing leaks from outside a session");
        }
    }

