    #[test]
    fn deterministic_and_order_independent() {
        let fns = vec![
            f("todos:add", FunctionKind::Mutation, Visibility::Public, "{ text: string, }", "Id<\"todos\">"),
            f("todos:list", FunctionKind::Query, Visibility::Public, "{ s?: Status | null, }", "Array<Doc<\"todos\">>"),
            f("misc:ping", FunctionKind::Action, Visibility::Public, "Record<symbol, never>", "string"),
        ];
        let tables = vec![
            TableTs { name: "todos".into(), ts: "{ text: string, status: Status, }".into() },
            TableTs { name: "notes".into(), ts: "{ body: string, }".into() },
        ];
        let types = vec![
            TypeDecl { name: "Status".into(), decl: "export type Status = \"open\" | \"done\";".into() },
            TypeDecl { name: "Extra".into(), decl: "export type Extra = { n: number, };".into() },
            TypeDecl { name: "Status".into(), decl: "export type Status = \"open\" | \"done\";".into() },
        ];
        let a = render(&fns, &tables, &types).unwrap();
        let (mut fns2, mut tables2, mut types2) = (fns.clone(), tables.clone(), types.clone());
        fns2.reverse();
        tables2.reverse();
        types2.reverse();
        let b = render(&fns2, &tables2, &types2).unwrap();
        assert_eq!(a, b);
        assert_eq!(a, render(&fns, &tables, &types).unwrap());

        // Tables and types sorted, types deduplicated.
        let dm = &a.data_model_ts;
        assert!(dm.contains("export type DataModel = {\n  \"notes\": { body: string, };\n  \"todos\": {"), "{dm}");
        assert_eq!(dm.matches("export type Status").count(), 1);
        assert!(dm.find("export type Extra").unwrap() < dm.find("export type Status").unwrap());
        // Only used names are imported; zero-arg functions use Record<string, never>.
        let api = &a.api_ts;
        assert!(api.contains("import type { Doc, Id, Status } from \"./dataModel\";\n"), "{api}");
        assert!(api.contains("ping: makeFunctionReference<\"action\", Record<string, never>, string>"), "{api}");
        assert!(!api.contains("symbol"));
    }

