//! TypeScript codegen: turns the registered tables and public functions into `dataModel.ts`, `api.ts` and
//! `index.ts` for the client packages (`@ferrix/client`, `@ferrix/react`, `@ferrix/svelte`).
//!
//! - `dataModel.ts` declares `DataModel` (table name → the table struct's TS object type), `TableNames`, `Id<T>`,
//!   `Doc<T>` (the table type plus the system fields), and every named user type that a table or a public function
//!   signature refers to (e.g. a `#[derive(TS)] enum Status`), recursively. `SystemDataModel` holds the few system
//!   tables apps may reference ([`REFERENCEABLE_SYSTEM_TABLES`], i.e. `_users`), so `Id<"_users">` type-checks.
//! - `api.ts` exports a nested `api` object of function references: path `"a/b:fn"` becomes `api.a.b.fn`, a root
//!   path `"fn"` becomes `api.fn`. Internal functions are left out.
//!
//! Named user types are discovered through [`crate::__private::ts_inline`]: while a codegen session is active on
//! the current thread, every call also walks ts-rs' dependency graph of its type and records the declarations.
//!
//! The output is deterministic (sorted keys, fixed formatting, 2-space indentation), and [`write_files`] only
//! rewrites files whose content changed, so a dev server watching the output (Vite HMR) doesn't loop.

use std::any::TypeId;
use std::cell::RefCell;
use std::collections::{BTreeMap, BTreeSet, HashSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::{Context, bail};
use ts_rs::{TS, TypeVisitor};

use crate::private::{FunctionKind, Visibility, ts_config};
use crate::runtime::{FunctionInfo, Registry, registered_tables, registry};
use crate::schema::TableDef;

/// File names written by [`write`].
pub const DATA_MODEL_FILE: &str = "dataModel.ts";
pub const API_FILE: &str = "api.ts";
pub const INDEX_FILE: &str = "index.ts";

const HEADER: &str = "/* eslint-disable */\n// Generated by `ferrix codegen`. Do not edit.\n";

/// Names that the generated files declare or import themselves; user types must not use them.
const RESERVED_TYPE_NAMES: &[&str] =
    &["DataModel", "SystemDataModel", "TableNames", "Id", "Doc", "GenericId", "api", "makeFunctionReference"];

/// System tables that app tables and functions may refer to (`Id<User>` → `Id<"_users">`). They are declared in
/// `SystemDataModel`, apart from the app's `DataModel`; every other `_`-prefixed table is left out.
pub const REFERENCEABLE_SYSTEM_TABLES: &[&str] = &["_users"];

/// The generated TypeScript sources.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFiles {
    pub data_model_ts: String,
    pub api_ts: String,
    pub index_ts: String,
}

impl GeneratedFiles {
    /// `(file name, content)` for every file, in a fixed order.
    pub fn files(&self) -> [(&'static str, &str); 3] {
        [(DATA_MODEL_FILE, &self.data_model_ts), (API_FILE, &self.api_ts), (INDEX_FILE, &self.index_ts)]
    }
}

/// A named TS type declaration collected from a user type, e.g. `export type Status = "open" | "done";`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TypeDecl {
    /// The TS identifier (without generic parameters).
    pub name: String,
    /// The full declaration, including JSDoc and `export`.
    pub decl: String,
}

/// A table as seen by codegen.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TableTs {
    pub name: String,
    /// The inline TS object type of the table struct.
    pub ts: String,
}

// ---------------------------------------------------------------------------------------------------------------------
// Dependency collection
// ---------------------------------------------------------------------------------------------------------------------

thread_local! {
    static SESSION: RefCell<Option<Collector>> = const { RefCell::new(None) };
}

#[derive(Default)]
struct Collector {
    seen: HashSet<TypeId>,
    decls: BTreeMap<String, TypeDecl>,
    errors: Vec<String>,
}

impl TypeVisitor for Collector {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        // Types without an output path are built-ins (`string`, `Array<..>`, maps, ...) or have a custom `TS` impl
        // without a declaration, like ferrix' own `Id<T>` / `Doc<T>`, which codegen declares itself.
        if T::output_path().is_none() || !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        let cfg = ts_config();
        let name = T::ident(cfg);
        let decl = render_decl(T::docs(), &T::decl(cfg));
        match self.decls.get(&name) {
            Some(existing) if existing.decl != decl => self.errors.push(format!(
                "two different Rust types are both named `{name}` in TypeScript; rename one with #[ts(rename = \"...\")]"
            )),
            Some(_) => {}
            None => {
                self.decls.insert(name.clone(), TypeDecl { name, decl });
            }
        }
        // The declaration refers to its own dependencies by name.
        T::visit_dependencies(self);
    }
}

fn render_decl(docs: Option<String>, decl: &str) -> String {
    let mut out = String::new();
    if let Some(docs) = docs {
        out.push_str(docs.trim_end());
        out.push('\n');
    }
    let decl = normalize_ts(decl.trim());
    out.push_str("export ");
    out.push_str(&decl);
    if !decl.ends_with(';') && !decl.ends_with('}') {
        out.push(';');
    }
    out
}

/// Called by `__private::ts_inline::<T>()`: if a session is active, record the named types that `T::inline()`
/// refers to. `T::visit_dependencies` visits exactly those (for a derived struct: its field types; for
/// `Vec<S>` / `Option<S>` / maps, which inline `S`: the dependencies of `S`).
pub(crate) fn collect_dependencies<T: TS + ?Sized + 'static>() {
    // Take the collector out while visiting, so that nothing can observe a borrowed RefCell.
    let Some(mut collector) = SESSION.with(|s| s.borrow_mut().take()) else { return };
    T::visit_dependencies(&mut collector);
    SESSION.with(|s| *s.borrow_mut() = Some(collector));
}

/// Run `f` with a dependency-collection session on this thread; returns its result and the collected declarations.
fn with_session<R>(f: impl FnOnce() -> R) -> crate::Result<(R, Vec<TypeDecl>)> {
    struct Reset(Option<Collector>);
    impl Drop for Reset {
        fn drop(&mut self) {
            let previous = self.0.take();
            SESSION.with(|s| *s.borrow_mut() = previous);
        }
    }
    let previous = SESSION.with(|s| s.borrow_mut().replace(Collector::default()));
    let _reset = Reset(previous);
    let out = f();
    let collector = SESSION.with(|s| s.borrow_mut().take()).unwrap_or_default();
    if !collector.errors.is_empty() {
        bail!("codegen: {}", collector.errors.join("; "));
    }
    Ok((out, collector.decls.into_values().collect()))
}

