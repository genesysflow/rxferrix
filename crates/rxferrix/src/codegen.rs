/// Generate the TS files for the public functions in `registry` and for `tables`.
pub fn generate(registry: &Registry, tables: &[TableDef]) -> crate::Result<GeneratedFiles> {
    let ((functions, tables), types) = with_session(|| {
        let functions: Vec<FunctionInfo> = registry
            .defs()
            .filter(|(path, def)| def.visibility == Visibility::Public && !crate::private::is_system_path(path))
            .map(|(path, def)| {
                let (args_ts, output_ts) = (def.ts)();
                FunctionInfo {
                    path: path.to_string(),
                    kind: def.handler.kind(),
                    visibility: def.visibility,
                    dev_only: def.dev_only,
                    args_ts,
                    output_ts,
                    docs: def.docs.to_string(),
                }
            })
            .collect();
        let tables: Vec<TableTs> = tables
            .iter()
            // System tables are internal to rxferrix, except the few that apps may reference.
            .filter(|t| !t.name.starts_with('_') || REFERENCEABLE_SYSTEM_TABLES.contains(&t.name))
            .map(|t| TableTs { name: t.name.to_string(), ts: (t.ts)() })
            .collect();
        (functions, tables)
    })?;
    render(&functions, &tables, &types)
}

/// Generate from the global registry and the linked-in tables, and write the files into `out_dir` (created if
/// missing). Returns the paths of the files whose content changed.
pub fn write(out_dir: impl AsRef<Path>) -> crate::Result<Vec<PathBuf>> {
    let files = generate(registry()?, &registered_tables())?;
    write_files(out_dir, &files)
}

/// Write `files` into `out_dir`, skipping files whose content is already up to date. Returns the changed paths.
pub fn write_files(out_dir: impl AsRef<Path>, files: &GeneratedFiles) -> crate::Result<Vec<PathBuf>> {
    let out_dir = out_dir.as_ref();
    std::fs::create_dir_all(out_dir).with_context(|| format!("creating {}", out_dir.display()))?;
    let mut changed = Vec::new();
    for (name, content) in files.files() {
        let path = out_dir.join(name);
        if std::fs::read_to_string(&path).is_ok_and(|old| old == content) {
            continue;
        }
        // Write a temp file and rename it, so a watcher never sees a half-written file.
        let tmp = out_dir.join(format!(".{name}.tmp"));
        std::fs::write(&tmp, content).with_context(|| format!("writing {}", tmp.display()))?;
        std::fs::rename(&tmp, &path).with_context(|| format!("writing {}", path.display()))?;
        changed.push(path);
    }
    Ok(changed)
}

/// Render the files from already-computed inputs. Internal functions are skipped. Pure and deterministic: the
/// output depends only on the inputs as sets (their order doesn't matter).
pub fn render(functions: &[FunctionInfo], tables: &[TableTs], types: &[TypeDecl]) -> crate::Result<GeneratedFiles> {
    // User types: sorted by name, deduplicated, no clashes with the names the generated files use.
    let mut user_types: BTreeMap<&str, &TypeDecl> = BTreeMap::new();
    for t in types {
        if RESERVED_TYPE_NAMES.contains(&t.name.as_str()) {
            bail!(
                "codegen: the type name `{}` is reserved by the generated code; rename the Rust type with \
                 #[ts(rename = \"...\")]",
                t.name
            );
        }
        if let Some(prev) = user_types.insert(&t.name, t)
            && prev.decl != t.decl
        {
            bail!("codegen: two different types are named `{}`", t.name);
        }
    }

    // dataModel.ts
    let mut all_tables: Vec<&TableTs> = tables.iter().collect();
    all_tables.sort_by(|a, b| a.name.cmp(&b.name));
    if let Some(w) = all_tables.windows(2).find(|w| w[0].name == w[1].name) {
        bail!("codegen: table `{}` is defined twice", w[0].name);
    }
    let (system_tables, tables): (Vec<&TableTs>, Vec<&TableTs>) =
        all_tables.into_iter().partition(|t| t.name.starts_with('_'));
    let mut dm = String::from(HEADER);
    dm.push_str("import type { Id as GenericId } from \"@rxferrix/client\";\n\n");
    dm.push_str("/** Every table, mapped to the type of its documents (without the system fields). */\n");
    if tables.is_empty() {
        dm.push_str("export type DataModel = {};\n");
    } else {
        dm.push_str("export type DataModel = {\n");
        for t in &tables {
            let _ = writeln!(dm, "  {}: {};", json_str(&t.name), format_ts(&normalize_ts(t.ts.trim()), 1));
        }
        dm.push_str("};\n");
    }
    dm.push_str("\n/** Built-in rxferrix tables that app documents may reference, e.g. `Id<\"_users\">`. */\n");
    if system_tables.is_empty() {
        dm.push_str("export type SystemDataModel = {};\n");
    } else {
        dm.push_str("export type SystemDataModel = {\n");
        for t in &system_tables {
            let _ = writeln!(dm, "  {}: {};", json_str(&t.name), format_ts(&normalize_ts(t.ts.trim()), 1));
        }
        dm.push_str("};\n");
    }
    dm.push_str(
        "\n/** The name of a table. */\n\
         export type TableNames = keyof DataModel;\n\
         \n/** A document id of table `T` (an app table, or a system table from `SystemDataModel`). At runtime a \
         plain string. */\n\
         export type Id<T extends TableNames | keyof SystemDataModel> = GenericId<T>;\n\
         \n/** A stored document of table `T`, with its system fields. */\n\
         export type Doc<T extends TableNames | keyof SystemDataModel> = (DataModel & SystemDataModel)[T] & \
         { _id: Id<T>; _creationTime: number };\n",
    );
    for t in user_types.values() {
        dm.push('\n');
        dm.push_str(&t.decl);
        dm.push('\n');
    }

    // api.ts
    let mut root: BTreeMap<String, Node> = BTreeMap::new();
    let mut dev_root: BTreeMap<String, Node> = BTreeMap::new();
    for f in functions.iter().filter(|f| f.visibility == Visibility::Public) {
        insert_function(if f.dev_only { &mut dev_root } else { &mut root }, f)?;
    }
    let mut body = String::new();
    if root.is_empty() {
        body.push_str("export const api = {} as const;\n");
    } else {
        body.push_str("export const api = {\n");
        render_tree(&mut body, &root, 1);
        body.push_str("} as const;\n");
    }
    if !dev_root.is_empty() {
        body.push_str(
            "\n/** Dev-only functions (`#[query(dev_only)]`, ...): the server refuses them unless it runs with `--dev`. */\n",
        );
        body.push_str("export const devApi = {\n");
        render_tree(&mut body, &dev_root, 1);
        body.push_str("} as const;\n");
    }
    // Doc comments don't count (and their prose, apostrophes included, mustn't be read as code).
    let code = without_comments(&body);
    let used = identifiers(&code);
    let imported: Vec<&str> =
        ["Doc", "Id"].into_iter().chain(user_types.keys().copied()).filter(|n| used.contains(*n)).collect();
    let mut api = String::from(HEADER);
    if !root.is_empty() || !dev_root.is_empty() {
        api.push_str("import { makeFunctionReference } from \"@rxferrix/client\";\n");
    }
    if !imported.is_empty() {
        let mut sorted = imported;
        sorted.sort_unstable();
        let _ = writeln!(api, "import type {{ {} }} from \"./dataModel\";", sorted.join(", "));
    }
    api.push_str("\n/** References to every public function, for `useQuery(api.module.fn, args)` and friends. */\n");
    api.push_str(&body);

    let index = format!("{HEADER}export * from \"./api\";\nexport * from \"./dataModel\";\n");
    Ok(GeneratedFiles { data_model_ts: dm, api_ts: api, index_ts: index })
}

enum Node<'a> {
    Function(&'a FunctionInfo),
    Module(BTreeMap<String, Node<'a>>),
}

fn insert_function<'a>(root: &mut BTreeMap<String, Node<'a>>, f: &'a FunctionInfo) -> crate::Result<()> {
    let (modules, name) = match f.path.split_once(':') {
        Some((m, n)) => (m.split('/').collect::<Vec<_>>(), n),
        None => (Vec::new(), f.path.as_str()),
    };
    if name.is_empty() || modules.iter().any(|m| m.is_empty()) {
        bail!("codegen: invalid function path `{}`", f.path);
    }
    let mut level = root;
    for (i, module) in modules.iter().enumerate() {
        let node = level.entry(module.to_string()).or_insert_with(|| Node::Module(BTreeMap::new()));
        level = match node {
            Node::Module(children) => children,
            Node::Function(other) => bail!(
                "codegen: `api.{}` would be both the function `{}` and the module `{}` (of `{}`); rename one of them",
                modules[..=i].join("."),
                other.path,
                modules[..=i].join("/"),
                f.path
            ),
        };
    }
    match level.get(name) {
        None => {
            level.insert(name.to_string(), Node::Function(f));
            Ok(())
        }
        Some(Node::Module(children)) => {
            let example = first_function(children).map(|g| g.path.as_str()).unwrap_or("?");
            let qualified: Vec<&str> = modules.iter().copied().chain([name]).collect();
            bail!(
                "codegen: `api.{}` would be both the function `{}` and the module `{}` (of `{example}`); rename one of them",
                qualified.join("."),
                f.path,
                qualified.join("/"),
            )
        }
        Some(Node::Function(_)) => bail!("codegen: two functions at path `{}`", f.path),
    }
}

fn first_function<'a>(level: &BTreeMap<String, Node<'a>>) -> Option<&'a FunctionInfo> {
    level.values().find_map(|n| match n {
        Node::Function(f) => Some(*f),
        Node::Module(children) => first_function(children),
    })
}

fn render_tree(out: &mut String, level: &BTreeMap<String, Node>, depth: usize) {
    let pad = "  ".repeat(depth);
    for (key, node) in level {
        let key = property_key(key);
        match node {
            Node::Function(f) => {
                let docs: Vec<String> = f.docs.lines().map(|l| l.trim_end().to_string()).collect();
                out.push_str(&jsdoc(trim_blank_lines(&docs), &pad));
                let kind = match f.kind {
                    FunctionKind::Query => "query",
                    FunctionKind::Mutation => "mutation",
                    FunctionKind::Action => "action",
                };
                let _ = writeln!(
                    out,
                    "{pad}{key}: makeFunctionReference<\"{kind}\", {}, {}>(\"{kind}\", {}),",
                    format_ts(&normalize_ts(f.args_ts.trim()), depth),
                    format_ts(&normalize_ts(f.output_ts.trim()), depth),
                    json_str(&f.path),
                );
            }
            Node::Module(children) => {
                let _ = writeln!(out, "{pad}{key}: {{");
                render_tree(out, children, depth + 1);
                let _ = writeln!(out, "{pad}}},");
            }
        }
    }
}

/// ts-rs renders an empty struct (e.g. the args of a zero-param function) as `Record<symbol, never>`; the client
/// expects `Record<string, never>`, which reads better and accepts `{}` the same way.
fn normalize_ts(ts: &str) -> String {
    ts.replace("Record<symbol, never>", "Record<string, never>")
}

fn json_str(s: &str) -> String {
    serde_json::to_string(s).expect("strings serialize")
}

// ---------------------------------------------------------------------------------------------------------------------
// Formatting
// ---------------------------------------------------------------------------------------------------------------------

/// Lays out the object types in a ts-rs type expression that has field doc comments: ts-rs writes
/// `{ a: string, \n/**\n * Docs.\n */\nb: number, }` on one line with the comments spliced in; an object type with a
/// documented field becomes one field per line, each JSDoc on its own lines above its field, indented by two spaces
/// per level (`depth` is the level of the line the type starts on). Object types without documented fields are kept
/// as they are (also when nested in a documented one), so undocumented code generates exactly what it did.
pub fn format_ts(ts: &str, depth: usize) -> String {
    if !ts.contains("/**") {
        return ts.to_string();
    }
    let bytes = ts.as_bytes();
    let mut out = String::with_capacity(ts.len() + 64);
    let mut i = 0;
    while i < bytes.len() {
        match bytes[i] {
            b'"' | b'\'' | b'`' => {
                let end = skip_string(bytes, i);
                out.push_str(&ts[i..end]);
                i = end;
            }
            b'/' if bytes.get(i + 1) == Some(&b'*') => {
                let end = skip_comment(bytes, i);
                out.push_str(&ts[i..end]);
                i = end;
            }
            b'{' => {
                let end = matching_brace(bytes, i);
                let inner = &ts[i + 1..end.saturating_sub(1).max(i + 1)];
                out.push_str(&format_object(inner, depth));
                i = end;
            }
            _ => {
                let c = ts[i..].chars().next().expect("in bounds");
                out.push(c);
                i += c.len_utf8();
            }
        }
    }
    out
}

/// One object type (`inner` is between its braces).
fn format_object(inner: &str, depth: usize) -> String {
    let items: Vec<(Vec<String>, &str)> = split_top_level(inner)
        .into_iter()
        .map(leading_docs)
        .filter(|(docs, body)| !docs.is_empty() || !body.is_empty())
        .collect();
    if items.iter().all(|(docs, _)| docs.is_empty()) {
        return format!("{{{}}}", format_ts(inner, depth));
    }
    let pad = "  ".repeat(depth + 1);
    let mut out = String::from("{\n");
    for (docs, body) in items {
        out.push_str(&jsdoc(&docs, &pad));
        out.push_str(&pad);
        out.push_str(&format_ts(body, depth + 1));
        out.push_str(",\n");
    }
    out.push_str(&"  ".repeat(depth));
    out.push('}');
    out
}

/// `ts` without its `/* .. */` comments.
fn without_comments(ts: &str) -> String {
    let mut out = String::with_capacity(ts.len());
    let mut rest = ts;
    while let Some(start) = rest.find("/*") {
        out.push_str(&rest[..start]);
        rest = rest[start + 2..].find("*/").map_or("", |end| &rest[start + 2 + end + 2..]);
    }
    out.push_str(rest);
    out
}

/// `lines` without its leading and trailing empty lines.
fn trim_blank_lines(lines: &[String]) -> &[String] {
    let start = lines.iter().position(|l| !l.is_empty()).unwrap_or(lines.len());
    let end = lines.iter().rposition(|l| !l.is_empty()).map_or(start, |i| i + 1);
    &lines[start..end]
}

/// `/** text */` for one line, a `/**` / ` * line` / ` */` block otherwise; each line starts with `pad`.
fn jsdoc(lines: &[String], pad: &str) -> String {
    match lines {
        [] => String::new(),
        [line] => format!("{pad}/** {line} */\n"),
        lines => {
            let mut out = format!("{pad}/**\n");
            for line in lines {
                if line.is_empty() {
                    let _ = writeln!(out, "{pad} *");
                } else {
                    let _ = writeln!(out, "{pad} * {line}");
                }
            }
            let _ = writeln!(out, "{pad} */");
            out
        }
    }
}

/// Splits an object type's body at its top-level commas; items are trimmed.
fn split_top_level(s: &str) -> Vec<&str> {
    let bytes = s.as_bytes();
    let (mut items, mut start, mut nesting, mut i) = (Vec::new(), 0, 0i32, 0);
    while i < bytes.len() {
        match bytes[i] {
            b'"' | b'\'' | b'`' => {
                i = skip_string(bytes, i);
                continue;
            }
            b'/' if bytes.get(i + 1) == Some(&b'*') => {
                i = skip_comment(bytes, i);
                continue;
            }
            b'{' | b'[' | b'(' | b'<' => nesting += 1,
            b'}' | b']' | b')' | b'>' => nesting -= 1,
            b',' if nesting == 0 => {
                items.push(s[start..i].trim());
                start = i + 1;
            }
            _ => {}
        }
        i += 1;
    }
    items.push(s[start..].trim());
    items
}

/// The JSDoc comments at the start of an object type item (as text lines), and the rest of it.
fn leading_docs(mut item: &str) -> (Vec<String>, &str) {
    let mut lines = Vec::new();
    while let Some(rest) = item.strip_prefix("/**") {
        let Some(end) = rest.find("*/") else { break };
        for line in rest[..end].lines() {
            let line = line.trim();
            let line = line.strip_prefix('*').map_or(line, |l| l.strip_prefix(' ').unwrap_or(l));
            lines.push(line.trim_end().to_string());
        }
        item = rest[end + 2..].trim_start();
    }
    while lines.first().is_some_and(String::is_empty) {
        lines.remove(0);
    }
    while lines.last().is_some_and(String::is_empty) {
        lines.pop();
    }
    (lines, item)
}

/// The index just past the string literal starting at `start`.
fn skip_string(bytes: &[u8], start: usize) -> usize {
    let quote = bytes[start];
    let mut i = start + 1;
    while i < bytes.len() && bytes[i] != quote {
        i += if bytes[i] == b'\\' { 2 } else { 1 };
    }
    (i + 1).min(bytes.len())
}

/// The index just past the `/* .. */` comment starting at `start`.
fn skip_comment(bytes: &[u8], start: usize) -> usize {
    let mut i = start + 2;
    while i + 1 < bytes.len() && !(bytes[i] == b'*' && bytes[i + 1] == b'/') {
        i += 1;
    }
    (i + 2).min(bytes.len())
}

/// The index just past the `}` matching the `{` at `start` (or the end of the input).
fn matching_brace(bytes: &[u8], start: usize) -> usize {
    let (mut depth, mut i) = (0, start);
    while i < bytes.len() {
        match bytes[i] {
            b'"' | b'\'' | b'`' => {
                i = skip_string(bytes, i);
                continue;
            }
            b'/' if bytes.get(i + 1) == Some(&b'*') => {
                i = skip_comment(bytes, i);
                continue;
            }
            b'{' => depth += 1,
            b'}' => {
                depth -= 1;
                if depth == 0 {
                    return i + 1;
                }
            }
            _ => {}
        }
        i += 1;
    }
    bytes.len()
}

fn is_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    chars.next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

fn property_key(s: &str) -> String {
    if is_identifier(s) { s.to_string() } else { json_str(s) }
}

/// The identifiers in a TS snippet, ignoring string literals.
fn identifiers(ts: &str) -> BTreeSet<&str> {
    let mut out = BTreeSet::new();
    let bytes = ts.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        let c = bytes[i];
        if c == b'"' || c == b'\'' || c == b'`' {
            i += 1;
            while i < bytes.len() && bytes[i] != c {
                i += if bytes[i] == b'\\' { 2 } else { 1 };
            }
            i += 1;
        } else if c.is_ascii_alphabetic() || c == b'_' || c == b'$' {
            let start = i;
            while i < bytes.len() && (bytes[i].is_ascii_alphanumeric() || bytes[i] == b'_' || bytes[i] == b'$') {
                i += 1;
            }
            out.insert(&ts[start..i]);
        } else {
            i += 1;
        }
    }
    out
}

